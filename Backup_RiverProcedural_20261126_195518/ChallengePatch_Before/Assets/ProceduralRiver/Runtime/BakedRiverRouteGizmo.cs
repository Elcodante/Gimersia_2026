using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Edit-time visualization of the baked main route and optional rock-only branches.
/// Gizmos do not affect gameplay or runtime physics.
/// </summary>
[DisallowMultipleComponent]
public sealed class BakedRiverRouteGizmo : MonoBehaviour
{
    [SerializeField] private List<Vector3> routePoints = new List<Vector3>();
    [SerializeField] private List<Vector3> anchorPoints = new List<Vector3>();
    [SerializeField] private List<Vector3> branchEdgePoints = new List<Vector3>();
    [SerializeField] private List<Vector3> branchAnchorPoints = new List<Vector3>();

    // Kept for compatibility with scenes generated by the earlier static baker.
    public void SetRoute(List<Vector3> route, List<Vector3> anchors)
    {
        SetRoute(route, anchors, null, null);
    }

    public void SetRoute(List<Vector3> route, List<Vector3> anchors,
        List<Vector3> branchEdges, List<Vector3> branchAnchors)
    {
        routePoints = route != null ? new List<Vector3>(route) : new List<Vector3>();
        anchorPoints = anchors != null ? new List<Vector3>(anchors) : new List<Vector3>();
        branchEdgePoints = branchEdges != null ? new List<Vector3>(branchEdges) : new List<Vector3>();
        branchAnchorPoints = branchAnchors != null ? new List<Vector3>(branchAnchors) : new List<Vector3>();
    }

    private void OnDrawGizmos()
    {
        if (routePoints == null || routePoints.Count < 2) return;

        // Main mandatory progression path.
        Gizmos.color = new Color(0.1f, 1f, 0.35f, 0.95f);
        for (int i = 0; i < routePoints.Count - 1; i++)
            Gizmos.DrawLine(routePoints[i], routePoints[i + 1]);

        // Optional alternate paths. These are not required to reach the finish.
        Gizmos.color = new Color(1f, 0.72f, 0.12f, 0.95f);
        if (branchEdgePoints != null)
        {
            for (int i = 0; i + 1 < branchEdgePoints.Count; i += 2)
                Gizmos.DrawLine(branchEdgePoints[i], branchEdgePoints[i + 1]);
        }

        Gizmos.color = new Color(0.2f, 0.9f, 1f, 0.95f);
        if (anchorPoints != null)
        {
            for (int i = 0; i < anchorPoints.Count; i++)
                Gizmos.DrawSphere(anchorPoints[i], 0.8f);
        }

        Gizmos.color = new Color(1f, 0.8f, 0.15f, 0.95f);
        if (branchAnchorPoints != null)
        {
            for (int i = 0; i < branchAnchorPoints.Count; i++)
                Gizmos.DrawSphere(branchAnchorPoints[i], 0.65f);
        }

#if UNITY_EDITOR
        UnityEditor.Handles.color = Color.white;
        UnityEditor.Handles.Label(routePoints[0] + Vector3.up * 2f, "START");
        if (anchorPoints != null)
        {
            for (int i = 0; i < anchorPoints.Count; i++)
                UnityEditor.Handles.Label(anchorPoints[i] + Vector3.up * 2f, "ROCK " + (i + 1).ToString("00"));
        }
        if (branchAnchorPoints != null)
        {
            for (int i = 0; i < branchAnchorPoints.Count; i++)
                UnityEditor.Handles.Label(branchAnchorPoints[i] + Vector3.up * 2f, "ALT " + (i + 1).ToString("00"));
        }
        UnityEditor.Handles.Label(routePoints[routePoints.Count - 1] + Vector3.up * 2f, "FINISH");
#endif
    }
}
